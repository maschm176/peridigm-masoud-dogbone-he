#!/usr/bin/env bash
set -euo pipefail

# Local Docker-based replacement for the original TACC Stampede
# (ibrun/SLURM/$HOME/projects) launch. create_input_deck.py and
# post-process.py need lxml/netCDF4, which are only installed inside the
# peridigm-masoud image, so the whole inner workflow runs in one container.
IMAGE=peridigm-masoud:latest
# 4 ranks measured as the sweet spot: ~4.3x speedup over 1 rank (super-linear),
# vs. diminishing returns beyond that (8 ranks only adds another ~1.4x).
# Requires the mesh pre-decomposed via `decomp -p 4 mesh.g` in mesh_tensile/.
NUM_PRC=${NUM_PRC:-4}

# Input arguments (generated by Dakota)
InputParameters=$1
OutputResult=$2

CALDIR=$(cd "$(dirname "$0")" && pwd)

cd "$CALDIR/Tests"

rm -f Obj*

cp "../$InputParameters" .

docker run --rm --platform linux/amd64 -v "$CALDIR/Tests":/output -w /output "$IMAGE" bash -c "
set -e
python3 create_input_deck.py $InputParameters
rm -f $InputParameters
if [ $NUM_PRC -gt 1 ]; then
  mpirun --allow-run-as-root -np $NUM_PRC Peridigm InputFileLongitudinal.xml
else
  Peridigm InputFileLongitudinal.xml
fi
python3 post-process.py
"

cd ..

# Compute the objective function for Dakota
python3 compute_objective_function.py "$OutputResult"
